export type SyllableFixtureEntry = {
	word: string;
	accepted: string[][];
};

/** Turns "a|b / c|d" fixture lines into a word and its accepted splits. */
export const parseSyllableFixture = (
	lines: readonly string[],
): SyllableFixtureEntry[] =>
	lines.map((line) => {
		const accepted = line.split(" / ").map((split) => split.split("|"));
		return { word: accepted[0].join(""), accepted };
	});
