import { Checkbox } from "@radix-ui/themes";
import { type Atom, atom, useAtomValue, useStore } from "jotai";
import { useSetImmerAtom } from "jotai-immer";
import { type ReactNode, useId, useMemo } from "react";
import { ActionTooltip } from "$/components/ActionTooltip";
import {
	lyricLinesAtom,
	selectedLinesAtom,
	selectedWordsAtom,
} from "$/states/main.ts";
import type { LyricLine, LyricWord } from "$/types/ttml";
import type { KeyBindingsConfig } from "$/utils/keybindings";
import { RibbonLabel } from "../RibbonToggle";

import {
	applySelectedField,
	getSelectedFieldValue,
	MULTIPLE_VALUES,
} from "./selection-values";
export function CheckboxField<
	L extends Word extends true ? LyricWord : LyricLine,
	F extends keyof L,
	V extends L[F] extends boolean ? boolean : never,
	Word extends boolean | undefined = undefined,
>({
	label,
	description,
	isWordField,
	fieldName,
	defaultValue,
	icon,
	shortcut,
}: {
	label: string;
	/** Shown before the label, for role fields. */
	icon?: ReactNode;
	/** One line for the tooltip on what the field does. */
	description?: string;
	isWordField: Word;
	fieldName: F;
	defaultValue: V;
	/** The command that toggles it, shown in the tooltip. */
	shortcut?: Atom<KeyBindingsConfig>;
}) {
	const itemAtom = useMemo(
		() => (isWordField ? selectedWordsAtom : selectedLinesAtom),
		[isWordField],
	);

	const editLyricLines = useSetImmerAtom(lyricLinesAtom);
	const store = useStore();

	const currentValueAtom = useMemo(
		() =>
			atom((get) => {
				const selectedItems = get(itemAtom);
				const lyricLines = get(lyricLinesAtom);
				return getSelectedFieldValue<L, F>(
					lyricLines.lyricLines,
					selectedItems,
					isWordField,
					fieldName,
					(value) => value,
				);
			}),
		[itemAtom, fieldName, isWordField],
	);
	const currentValue = useAtomValue(currentValueAtom);
	const isDisabledAtom = useMemo(
		() => atom((get) => get(itemAtom).size === 0),
		[itemAtom],
	);
	const isDisabled = useAtomValue(isDisabledAtom);
	const checkboxId = useId();

	return (
		<>
			<RibbonLabel
				label={label}
				description={description}
				shortcut={shortcut}
				htmlFor={checkboxId}
				icon={icon}
			/>
			<ActionTooltip
				label={label}
				description={description}
				shortcut={shortcut}
			>
				<Checkbox
					disabled={isDisabled}
					id={checkboxId}
					checked={
						currentValue
							? currentValue === MULTIPLE_VALUES
								? "indeterminate"
								: (currentValue as boolean)
							: defaultValue
					}
					onCheckedChange={(value) => {
						if (value === "indeterminate") return;
						editLyricLines((state) => {
							const selectedItems = store.get(itemAtom);
							state.lyricLines = applySelectedField<L, F>(
								state.lyricLines,
								selectedItems,
								isWordField,
								fieldName,
								value as L[F],
							);
							return state;
						});
					}}
				/>
			</ActionTooltip>
		</>
	);
}

